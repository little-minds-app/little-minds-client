#!/usr/bin/env python3
"""Generate original preschool-friendly Animal Sound Matching SFX (PCM WAV).

Commercial-safe: pure synthesis only — no third-party samples, no voice,
no copyrighted music. Deterministic LCG noise for clap bursts. Frequencies
and envelopes are distinct from Color Sorting while staying in the same
Happy Garden family.

Usage:
  python3 scripts/generate_animal_sound_matching_sfx.py
"""

from __future__ import annotations

import hashlib
import math
import struct
import wave
from pathlib import Path

SR = 22050
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "apps/mobile/assets/audio/animal_sound_matching/sfx"


def clamp(x: float) -> int:
    return max(-32767, min(32767, int(x)))


def write_wav(name: str, samples: list[float]) -> Path:
    path = OUT / name
    with wave.open(str(path), "w") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        frames = b"".join(struct.pack("<h", clamp(s * 32767.0)) for s in samples)
        w.writeframes(frames)
    return path


def env_adsr(i: int, n: int, a=0.01, d=0.08, s=0.55, r=0.25) -> float:
    t = i / max(n - 1, 1)
    if t < a:
        return t / a
    if t < a + d:
        return 1.0 - (1.0 - s) * ((t - a) / d)
    if t < 1.0 - r:
        return s
    return s * max(0.0, (1.0 - t) / r)


def tone(
    freq: float,
    dur: float,
    amp=0.45,
    a=0.01,
    d=0.08,
    s=0.5,
    r=0.3,
) -> list[float]:
    n = int(SR * dur)
    out = []
    for i in range(n):
        t = i / SR
        # Slightly different harmonic weighting vs Color Sorting SFX
        sig = math.sin(2 * math.pi * freq * t) + 0.12 * math.sin(
            4 * math.pi * freq * t
        )
        out.append(amp * env_adsr(i, n, a, d, s, r) * sig)
    return out


def noise_burst(dur: float, amp=0.35, bright=0.5) -> list[float]:
    n = int(SR * dur)
    out = []
    state = 0xC0DE_CAFE
    prev = 0.0
    for i in range(n):
        state = (1664525 * state + 1013904223) & 0xFFFFFFFF
        white = ((state / 0xFFFFFFFF) * 2.0) - 1.0
        prev = prev * (1.0 - bright) + white * bright
        out.append(amp * env_adsr(i, n, 0.002, 0.05, 0.25, 0.55) * prev)
    return out


def mix(*tracks: list[float]) -> list[float]:
    length = max((len(t) for t in tracks), default=0)
    out = [0.0] * length
    for t in tracks:
        for i, v in enumerate(t):
            out[i] += v
    peak = max((abs(v) for v in out), default=1.0) or 1.0
    if peak > 0.95:
        out = [v * (0.95 / peak) for v in out]
    return out


def concat(*parts: list[float], gap_ms: float = 0.0) -> list[float]:
    gap = [0.0] * int(SR * gap_ms / 1000.0)
    out: list[float] = []
    for i, p in enumerate(parts):
        if i:
            out.extend(gap)
        out.extend(p)
    return out


def pad(samples: list[float], lead_ms=0.0, trail_ms=20.0) -> list[float]:
    return (
        [0.0] * int(SR * lead_ms / 1000.0)
        + samples
        + [0.0] * int(SR * trail_ms / 1000.0)
    )


def write_readme() -> None:
    text = """# Animal Sound Matching SFX

Original preschool cue sounds in the Happy Garden family (distinct from Color Sorting).
Generated by `scripts/generate_animal_sound_matching_sfx.py` using original digital
synthesis only — no third-party samples.
"""
    (OUT / "README.md").write_text(text, encoding="utf-8")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)

    # Tap: brighter pair than Color Sorting (880/1174.66 vs ~932/1244)
    tap = mix(
        tone(880.0, 0.04, amp=0.36, a=0.002, d=0.045, s=0.18, r=0.62),
        tone(1174.66, 0.028, amp=0.17, a=0.001, d=0.038, s=0.1, r=0.72),
    )
    write_wav("tap_pop.wav", pad(tap, trail_ms=30))

    # Bounce: minor-third hop (E4 → G4) vs Color Sorting's M2 pair
    bounce = concat(
        tone(329.63, 0.072, amp=0.30, a=0.005, d=0.085, s=0.22, r=0.52),
        tone(392.0, 0.055, amp=0.24, a=0.004, d=0.075, s=0.18, r=0.58),
        gap_ms=22,
    )
    write_wav("drag_bounce.wav", pad(bounce, trail_ms=40))

    # Correct: B4 → D#5 fifth-ish lift (not the prior fifth pair)
    chime = concat(
        tone(493.88, 0.145, amp=0.40, a=0.01, d=0.11, s=0.42, r=0.42),
        tone(622.25, 0.175, amp=0.38, a=0.01, d=0.11, s=0.38, r=0.48),
        gap_ms=50,
    )
    write_wav("correct_chime.wav", pad(chime, trail_ms=50))

    clap = concat(
        noise_burst(0.052, amp=0.40, bright=0.58),
        noise_burst(0.048, amp=0.26, bright=0.52),
        gap_ms=75,
    )
    write_wav("soft_clap.wav", pad(clap, trail_ms=40))

    wrong = concat(
        tone(277.18, 0.115, amp=0.26, a=0.016, d=0.105, s=0.32, r=0.48),
        tone(233.08, 0.17, amp=0.22, a=0.016, d=0.125, s=0.28, r=0.52),
        gap_ms=38,
    )
    write_wav("wrong_soft.wav", pad(wrong, trail_ms=50))

    jingle_core = concat(
        tone(493.88, 0.108, amp=0.36, a=0.01, d=0.1, s=0.38, r=0.42),
        tone(622.25, 0.108, amp=0.34, a=0.01, d=0.1, s=0.38, r=0.42),
        tone(739.99, 0.115, amp=0.34, a=0.01, d=0.1, s=0.38, r=0.42),
        tone(987.77, 0.21, amp=0.38, a=0.01, d=0.115, s=0.33, r=0.52),
        gap_ms=42,
    )
    sparkle = mix(
        tone(1760.0, 0.078, amp=0.11, a=0.002, d=0.048, s=0.14, r=0.72),
        tone(2349.32, 0.058, amp=0.075, a=0.002, d=0.038, s=0.1, r=0.78),
    )
    jingle = mix(jingle_core, [0.0] * int(SR * 0.30) + sparkle)
    write_wav("complete_jingle.wav", pad(jingle, trail_ms=60))

    twinkle = concat(
        tone(1318.51, 0.048, amp=0.17, a=0.002, d=0.042, s=0.18, r=0.72),
        tone(1661.22, 0.055, amp=0.13, a=0.002, d=0.042, s=0.14, r=0.78),
        tone(2093.0, 0.048, amp=0.095, a=0.002, d=0.032, s=0.1, r=0.82),
        gap_ms=32,
    )
    write_wav("twinkle.wav", pad(twinkle, trail_ms=40))

    write_readme()

    for p in sorted(OUT.glob("*.wav")):
        data = p.read_bytes()
        sha = hashlib.sha256(data).hexdigest()
        with wave.open(str(p)) as w:
            dur = w.getnframes() / w.getframerate()
        print(f"{p.name:22} {len(data):6}B  {dur:.3f}s  sha256={sha}")

    print(f"Wrote {OUT / 'README.md'}")


if __name__ == "__main__":
    main()
